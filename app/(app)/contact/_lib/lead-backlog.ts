/**
 * 콜·지·기·소 「아직 미팅 안 잡은 영업기회」 세기 (순수).
 *
 * ## 왜 (2026-09-02 belie 신고)
 * STEP 1 에서 영업기회를 접수하면서 **접수일을 지난 날짜로** 적으면, 오늘 컨택관리에서
 * 그 건이 **유입 숫자에 안 보인다**. 콜·지·기·소 유입은 ADR-0029 에 따라
 * **「그 날짜에 접수한 건수」**(`leads.filter(접수일 === date).length`)라서, 접수일이
 * 8/20 이면 8/20 에만 잡히기 때문이다. 접수해 놓고 잊기 쉬운 구조였다.
 *
 * ## 왜 유입 숫자를 안 바꾸고 「따로 보여주기」로 갔나 (belie 선택 A)
 * 유입은 **하루치 칸**(01 영업관리 F)이고 주차·8주 누적은 그 칸들을 **더한다**. 미매칭 건을
 * 매칭될 때까지 매일 다시 세면 **같은 1건이 날짜 수만큼 중복 계상**돼 8주 유입이 부풀고
 * 퍼널 비율이 무너진다. 그래서 **저장값(F)은 ADR-0029 그대로 두고**, 화면에만 대기 건수를
 * 보여준다 — 통계는 한 자리도 안 바뀐다.
 *
 * 피커(미팅 잡을 때 고르는 목록)는 **이미** 미매칭 건을 접수일과 무관하게 계속 후보로 들고
 * 있다(`LeadPickerModal` 의 `!matched` 필터, lead-chain §4-1). 사라져 보이던 건 **숫자뿐**이라,
 * 이 표시는 이미 있는 사실을 드러내는 것이지 새 규칙을 만드는 게 아니다.
 */

/** `matched` 파생을 가진 발굴 후보의 최소 형태 — `/api/leads`(listLeadCandidates) 응답 기준. */
export interface LeadBacklogItem {
  matched?: boolean;
}

/**
 * 아직 미팅으로 이어지지 않은 영업기회 수. **접수일은 보지 않는다** — 지난 날짜 접수도
 * 매칭되기 전까지는 계속 대기 중이라는 게 이 숫자의 뜻이다.
 * 목록을 아직 못 받았으면(undefined) 0 — 로딩 중에 "0건"을 단정해 깜빡이지 않게 호출부가 숨긴다.
 */
export function countUnmatchedLeads(leads: LeadBacklogItem[] | undefined): number {
  if (!leads) return 0;
  return leads.filter((l) => !l.matched).length;
}
