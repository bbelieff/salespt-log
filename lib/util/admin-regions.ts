export interface Region {
  시도: Sido | "";
  시군구: string;
}

const ALIAS_KEYS = Object.keys(SIDO_ALIASES).sort((a, b) => b.length - a.length);

/** 한 낱말(토큰) → 짧은 시·도 이름. 없으면 "". */
export function sidoOf(token: string): Sido | "" {
  const t = token.trim();
  return SIDO_ALIASES[t] ?? "";
}

/**
 * 주소 글 → 시·도 / 시·군·구. 원문은 바꾸지 않는다.
 * · 첫머리의 시·도 표기를 찾고(「울산광역시」「울산」 둘 다), 이어지는 낱말에서 그 시·도의 시·군·구를 찾는다.
 * · 시·도 없이 시·군·구부터 쓴 주소(「수원시 장안구 …」)는 전국에서 그 이름이 하나뿐일 때만 시·도를 채운다(「중구」처럼 여럿이면 비움).
 * · 「경기 화성시」「서울 강남구 테헤란로」「경상남도창원시」(붙여 쓴 것)도 읽는다. 못 읽으면 빈 값.
 */
export function parseRegion(address: string): Region {
  const text = String(address ?? "").replace(/[()\[\],]/g, " ").replace(/\s+/g, " ").trim();
  if (!text) return { 시도: "", 시군구: "" };
  let sido: Sido | "" = "";
  let rest = text;
  for (const key of ALIAS_KEYS) {
    // 짧은 이름은 낱말 경계가 있어야 한다 — 「광주시 …」(경기 광주)를 광주광역시로 읽지 않게. 긴 공식 이름만 붙여 쓴 꼴을 허용.
    const next = text.charAt(key.length);
    const official = /(광역시|특별시|자치시|도)$/.test(key);
    if (text.startsWith(key) && (next === "" || next === " " || official)) {
      sido = SIDO_ALIASES[key]!;
      rest = text.slice(key.length).trim();
      break;
    }
  }
  const tokens = rest.split(" ").filter(Boolean);
  if (sido) {
    const list = SIGUNGU[sido];
    // 붙여 쓴 「창원시의창구」 같은 꼴도 앞부분이 맞으면 인정한다.
    for (const tok of tokens.slice(0, 3)) {
      const hit = list.find((name) => tok === name || tok.startsWith(name));
      if (hit) return { 시도: sido, 시군구: hit };
    }
    return { 시도: sido, 시군구: "" };
  }
  const first = tokens[0] ?? "";
  const owners = SIDO.filter((s) => SIGUNGU[s].some((name) => first === name || first.startsWith(name)));
  if (owners.length === 1) {
    const s = owners[0]!;
    return { 시도: s, 시군구: SIGUNGU[s].find((name) => first === name || first.startsWith(name))! };
  }
  return { 시도: "", 시군구: "" };
}
